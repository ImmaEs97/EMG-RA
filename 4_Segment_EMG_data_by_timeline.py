RUN_INDEX = 20

## Offset from device activation to first useful data (in seconds)
DEVICE_START_OFFSET = 0  # Offset in seconds

## Automatic calculation: useful duration = max(end_sec) of the timeline (already relative to the offset)
TOTAL_DURATION_FROM_DEVICE = max([end for (_, _, _, end, _) in TIMELINE])

## Sampling frequency (Hz)
SAMPLING_FREQUENCY = 50 # Sampling frequency

# Use automatic movement detection (True) or use offset directly as timeline start (False)
# Set to False when you have exact timing from video and don't need automatic detection
USE_AUTOMATIC_DETECTION = False

## Notes about the timeline (optional, for documentation)
TIMELINE_NOTES = """
Partecipant H20 (Day5_H6):
- DEVICE_START_OFFSET = 0s (timeline from the start of the file)
- Timeline was refined after inspecting the full recording plot generated by
    Plot_full_time_temp.py, then adjusted with the timeline overlay plot from
    Plot_timeline_overlay.py to verify the final segmentation boundaries
- fs = 50 Hz
"""


